class TestUpgradeBodyThatCannotBeRead:
    def test_a_with_block_is_unknown(self):
        # `op.batch_alter_table` roda as operações num `batch_op` que o
        # classificador não segue. Zero findings aqui sairia como "nada a
        # reportar" para uma migração que derruba coluna.
        finding = one(
            """
            with op.batch_alter_table("docs_signature") as batch_op:
                batch_op.drop_column("code")
            """
        )
        assert finding.severity is Severity.UNKNOWN
        assert "batch_alter_table" in finding.reason

    def test_an_operation_inside_a_conditional_is_unknown(self):
        source = migration(
            """
            if DIALECT == "postgresql":
                op.drop_column("t", "c")
            """
        )
        assert severities(source) == [Severity.UNKNOWN]

    def test_an_operation_inside_a_loop_is_unknown(self):
        source = migration(
            """
            for column in COLUMNS:
                op.drop_column("t", column)
            """
        )
        assert severities(source) == [Severity.UNKNOWN]

    def test_an_operation_inside_a_try_is_unknown(self):
        source = migration(
            """
            try:
                op.drop_column("t", "c")
            except Exception:
                pass
            """
        )
        assert severities(source) == [Severity.UNKNOWN]

    def test_an_assignment_in_the_body_is_unknown(self):
        # `conn = op.get_bind()` é o começo de um DDL que o classificador não lê.
        source = migration('conn = op.get_bind()\nconn.execute("DROP TABLE t")')
        assert max_severity(severities(source)) is Severity.UNKNOWN

    def test_a_helper_call_is_unknown_and_names_the_helper(self):
        finding = one("_recria_indices()")
        assert finding.severity is Severity.UNKNOWN
        assert "`_recria_indices`" in finding.reason

    def test_an_upgrade_defined_conditionally_is_unknown(self):
        source = (
            "from alembic import op\n"
            "if LEGACY:\n"
            "    def upgrade():\n"
            "        op.drop_table('t')\n"
            "else:\n"
            "    def upgrade():\n"
            "        pass\n"
        )
        finding = only(source)
        assert finding.severity is Severity.UNKNOWN
        assert "não é definida no corpo do módulo" in finding.reason

    def test_an_upgrade_defined_inside_a_try_is_unknown(self):
        source = (
            "from alembic import op\n"
            "try:\n"
            "    def upgrade():\n"
            "        op.drop_table('t')\n"
            "except ImportError:\n"
            "    pass\n"
        )
        assert only(source).severity is Severity.UNKNOWN

    def test_a_file_that_is_not_valid_python_is_unknown(self):
        assert only("def upgrade(:\n    pass\n").severity is Severity.UNKNOWN

    def test_an_operation_after_an_unreadable_statement_is_still_classified(self):
        # Desistir do arquivo inteiro esconderia o `drop_table` que vem depois.
        source = migration(
            """
            if LEGACY:
                op.drop_column("t", "c")
            op.drop_table("t")
            """
        )
        assert severities(source) == [Severity.UNKNOWN, Severity.BREAKING]


