"""Testes do parser de migrações do Alembic.

As migrações usadas aqui foram derivadas do corpus real do consumidor
Alembic/PostgreSQL — 13 arquivos em `app/alembic/versions/`, cujas 8 operações
distintas dentro de
`upgrade()` o classificador tem que cobrir sem devolver nenhum `unknown`. Onde
o corpus não cobre o caso exigido pelo aceite — `op.execute()`, `alter_column`,
`rename_table`, `create_primary_key` — a migração é inventada, mas com a forma
que um arquivo autogerado pelo Alembic teria.

Nenhum arquivo do corpus é copiado para cá: a suíte de fixtures é da QQ-2161.
"""

import string
import textwrap

import pytest

from detect.alembic import (
    _EXPANDERS,
    _OPERATIONS,
    _REFINERS,
    classify_migration,
)
from detect.severity import DUPLICATE, Severity, max_severity

# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

PREAMBLE = "from alembic import op\nimport sqlalchemy as sa\n"


def migration(upgrade: str, preamble: str = PREAMBLE, downgrade: str = "pass") -> str:
    """Um arquivo de versão do Alembic com `upgrade` no corpo da função."""
    return (
        f"{preamble}\n"
        "revision = 'a1b2c3'\n"
        "down_revision = 'z9y8x7'\n"
        "branch_labels = None\n"
        "depends_on = None\n"
        "\n"
        "def upgrade() -> None:\n"
        f"{textwrap.indent(textwrap.dedent(upgrade).strip(), ' ' * 4)}\n"
        "\n"
        "def downgrade() -> None:\n"
        f"{textwrap.indent(textwrap.dedent(downgrade).strip(), ' ' * 4)}\n"
    )


def severities(source: str) -> list[Severity]:
    return [finding.severity for finding in classify_migration(source)]


def only(source: str):
    """O único finding da migração — falha se houver mais de um."""
    findings = classify_migration(source)
    assert len(findings) == 1, findings
    return findings[0]


def one(upgrade: str):
    """O único finding de um corpo de `upgrade()`."""
    return only(migration(upgrade))


def severity_of(upgrade: str) -> Severity:
    return one(upgrade).severity


def placeholders(template: str) -> set[str]:
    return {field for _, field, _, _ in string.Formatter().parse(template) if field}


