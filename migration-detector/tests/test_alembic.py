class TestOpAlias:
    def test_the_corpus_import_binds_op(self):
        assert severity_of('op.drop_table("t")') is Severity.BREAKING

    def test_an_aliased_import_is_followed(self):
        source = migration(
            'alembic_op.drop_table("t")',
            preamble="from alembic import op as alembic_op\n",
        )
        assert severities(source) == [Severity.BREAKING]

    def test_a_module_import_with_an_alias_is_followed(self):
        source = migration('op.drop_table("t")', preamble="import alembic.op as op\n")
        assert severities(source) == [Severity.BREAKING]

    def test_a_name_that_is_not_the_alembic_op_is_not_an_operation(self):
        # Com `op` ligado a outro nome, `op.drop_table` é uma chamada qualquer.
        source = migration(
            'op.drop_table("t")', preamble="from alembic import op as alembic_op\n"
        )
        finding = only(source)
        assert finding.severity is Severity.UNKNOWN
        assert "`drop_table`" in finding.reason

    def test_a_qualified_call_is_not_read_as_an_operation(self):
        source = migration('alembic.op.drop_table("t")', preamble="import alembic\n")
        assert severities(source) == [Severity.UNKNOWN]

    def test_an_operation_called_through_a_variable_is_unknown(self):
        assert severity_of('OPS["drop"]("t")') is Severity.UNKNOWN

    def test_an_operation_out_of_the_table_is_unknown_and_names_itself(self):
        finding = one('op.create_foreign_key("fk", "a", "b", ["a_id"], ["id"])')
        assert finding.severity is Severity.UNKNOWN
        assert "`op.create_foreign_key`" in finding.reason


