class TestAddUniqueColumn:
    """A mesma regra do `AddField` único do Django.

    Só `server_default` preenche as linhas que já existem; o `default` do
    SQLAlchemy vale para insert novo e deixa as antigas em NULL.
    """

    @pytest.mark.parametrize(
        "column",
        (
            'sa.Column("slug", sa.String(20), server_default="", nullable=False, unique=True)',
            'sa.Column("slug", sa.String(20), server_default="x", nullable=True, unique=True)',
            'sa.Column("slug", sa.String(20), nullable=False, unique=True)',
        ),
    )
    def test_is_breaking(self, column):
        finding = one(f'op.add_column("doc", {column})')
        assert finding.severity is Severity.BREAKING
        assert DUPLICATE in finding.reason

    @pytest.mark.parametrize(
        "column",
        (
            'sa.Column("slug", sa.String(20), nullable=True, unique=True)',
            'sa.Column("slug", sa.String(20), default="x", nullable=True, unique=True)',
            'sa.Column("slug", sa.String(20), server_default=None, nullable=True, unique=True)',
            'sa.Column("slug", sa.String(20), server_default="", nullable=False, unique=False)',
        ),
    )
    def test_without_a_repeated_value_keeps_the_add_column_rule(self, column):
        assert severity_of(f'op.add_column("doc", {column})') is Severity.SAFE


class TestAddColumn:
    def test_nullable_column_is_safe(self):
        assert (
            severity_of(
                'op.add_column("docs_signature", sa.Column("external_id", sa.UUID(), nullable=True))'
            )
            is Severity.SAFE
        )

    def test_not_null_with_server_default_is_safe(self):
        # A forma de `cbec11662da5_column_added_and_constraint_widened`.
        assert (
            severity_of(
                'op.add_column("docs_ui_feedback",'
                ' sa.Column("type", sa.Integer(), server_default="1", nullable=False))'
            )
            is Severity.SAFE
        )

    def test_not_null_without_default_is_controlled(self):
        finding = one(
            'op.add_column("t", sa.Column("c", sa.Integer(), nullable=False))'
        )
        assert finding.severity is Severity.CONTROLLED
        assert "NOT NULL sem default" in finding.reason

    def test_a_column_without_nullable_is_controlled(self):
        # O Alembic autogerado sempre escreve `nullable=`; a ausência é sinal de
        # que o classificador está lendo algo que não veio do autogenerate.
        assert (
            severity_of('op.add_column("t", sa.Column("c", sa.Integer()))')
            is Severity.CONTROLLED
        )

    def test_a_column_the_classifier_cannot_read_is_unknown(self):
        finding = one('op.add_column("t", COLUMN)')
        assert finding.severity is Severity.UNKNOWN
        assert "`t`" in finding.reason

    def test_unpacked_arguments_are_unknown(self):
        assert severity_of("op.add_column(*SPEC)") is Severity.UNKNOWN

    def test_unpacked_arguments_inside_the_column_are_unknown(self):
        # A nulidade e o default que este refinador lê moram no `sa.Column`, não
        # no `add_column`: é lá dentro que o keyword ausente engana.
        assert (
            severity_of('op.add_column("t", sa.Column("c", sa.Integer(), **SPEC))')
            is Severity.UNKNOWN
        )

    def test_a_truthy_nullable_that_is_not_the_literal_true_is_controlled(self):
        # `nullable=1` não é `nullable=True`; ler o literal com `bool()` daria um
        # `safe` confiante a uma coluna cuja nulidade o arquivo não declara.
        assert (
            severity_of('op.add_column("t", sa.Column("c", sa.Integer(), nullable=1))')
            is Severity.CONTROLLED
        )

    def test_the_column_name_comes_from_the_sa_column_call(self):
        finding = one(
            'op.add_column("docs_signature", sa.Column("external_id", sa.UUID(), nullable=True))'
        )
        assert finding.reason == "Coluna `external_id` adicionada em `docs_signature`."


