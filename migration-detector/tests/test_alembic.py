class TestOpFIsNotAnOperation:
    def test_op_f_nested_in_create_index_yields_one_finding(self):
        # 42 ocorrências no corpus, todas como nome de índice.
        finding = one(
            'op.create_index(op.f("ix_docs_ai_feedback_rating"), "docs_ai_feedback",'
            ' ["rating"], unique=False)'
        )
        assert finding.severity is Severity.SAFE
        assert "Índice `ix_docs_ai_feedback_rating` criado em `docs_ai_feedback`." == (
            finding.reason
        )

    def test_op_f_nested_in_drop_index_yields_one_finding(self):
        finding = one(
            'op.drop_index(op.f("ix_docs_ai_feedback_rating"), table_name="docs_ai_feedback")'
        )
        assert finding.severity is Severity.CONTROLLED
        assert finding.reason.startswith(
            "Índice `ix_docs_ai_feedback_rating` removido de `docs_ai_feedback`"
        )

    def test_op_f_alone_does_not_raise_the_severity(self):
        assert severity_of('op.f("ix_t_c")') is Severity.NONE


