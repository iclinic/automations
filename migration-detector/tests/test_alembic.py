class TestUpgradeBody:
    def test_returns_one_finding_per_operation_in_order(self):
        source = migration(
            """
            op.add_column("docs_signature", sa.Column("external_id", sa.UUID(), nullable=True))
            op.drop_column("docs_signature", "code")
            """
        )
        assert severities(source) == [Severity.SAFE, Severity.BREAKING]

    def test_downgrade_is_ignored(self):
        # O corpus inteiro tem `drop_table` e `drop_column` no `downgrade()`.
        # Classificá-los pintaria de vermelho toda migração que sabe se desfazer.
        source = migration(
            'op.create_table("docs_list_card")',
            downgrade='op.drop_table("docs_list_card")',
        )
        assert severities(source) == [Severity.SAFE]

    def test_a_function_that_is_not_upgrade_is_ignored(self):
        source = migration(
            'op.create_table("t")',
            preamble=PREAMBLE + "\ndef helper():\n    op.drop_table('t')\n",
        )
        assert severities(source) == [Severity.SAFE]

    def test_a_docstring_in_the_body_is_not_an_operation(self):
        assert severities(migration('"""Cria a tabela."""\nop.create_table("t")')) == [
            Severity.SAFE
        ]

    def test_an_upgrade_that_only_passes_yields_no_findings(self):
        assert classify_migration(migration("pass")) == []

    def test_a_file_without_upgrade_yields_no_findings(self):
        source = "revision = 'a1'\ndown_revision = None\n"
        assert classify_migration(source) == []

    def test_the_last_upgrade_definition_wins(self):
        source = (
            "from alembic import op\n"
            "\n"
            "def upgrade():\n"
            "    op.create_table('t')\n"
            "\n"
            "def upgrade():\n"
            "    op.drop_table('t')\n"
        )
        assert severities(source) == [Severity.BREAKING]

    def test_comments_between_operations_are_not_operations(self):
        # Toda migração autogerada do corpus vem cercada de
        # `# ### commands auto generated by Alembic ###`.
        source = migration(
            """
            # ### commands auto generated by Alembic - please adjust! ###
            op.create_table("t")
            # ### end Alembic commands ###
            """
        )
        assert severities(source) == [Severity.SAFE]


