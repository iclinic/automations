class TestAlterColumn:
    def test_without_existing_type_is_unknown(self):
        finding = one('op.alter_column("t", "c", nullable=False)')
        assert finding.severity is Severity.UNKNOWN
        assert "não conhece a definição anterior" in finding.reason

    def test_a_type_change_is_breaking(self):
        finding = one(
            'op.alter_column("t", "c", type_=sa.String(length=100),'
            ' existing_type=sa.String(length=50))'
        )
        assert finding.severity is Severity.BREAKING
        assert "Tipo da coluna `c` de `t` alterado" in finding.reason

    def test_the_same_type_written_twice_is_not_a_type_change(self):
        assert (
            severity_of(
                'op.alter_column("t", "c", type_=sa.String(length=50),'
                ' existing_type=sa.String(length=50), nullable=True,'
                ' existing_nullable=False)'
            )
            is Severity.CONTROLLED
        )

    def test_becoming_not_null_is_breaking(self):
        finding = one(
            'op.alter_column("t", "c", existing_type=sa.Integer(),'
            ' nullable=False, existing_nullable=True)'
        )
        assert finding.severity is Severity.BREAKING
        assert "passou a NOT NULL" in finding.reason

    def test_becoming_nullable_is_controlled(self):
        finding = one(
            'op.alter_column("t", "c", existing_type=sa.Integer(),'
            ' nullable=True, existing_nullable=False)'
        )
        assert finding.severity is Severity.CONTROLLED
        assert "passou a aceitar NULL" in finding.reason

    def test_not_null_without_the_previous_nullability_is_unknown(self):
        finding = one(
            'op.alter_column("t", "c", existing_type=sa.Integer(), nullable=False)'
        )
        assert finding.severity is Severity.UNKNOWN
        assert "nulidade anterior" in finding.reason

    def test_a_nullability_that_did_not_change_is_not_reported_as_a_change(self):
        assert (
            severity_of(
                'op.alter_column("t", "c", existing_type=sa.Integer(),'
                ' nullable=False, existing_nullable=False,'
                ' server_default="1", existing_server_default=None)'
            )
            is Severity.CONTROLLED
        )

    def test_a_server_default_change_is_controlled(self):
        finding = one(
            'op.alter_column("t", "c", existing_type=sa.Integer(), server_default="1")'
        )
        assert finding.severity is Severity.CONTROLLED
        assert "Default da coluna `c` de `t` alterado." == finding.reason

    def test_a_rename_is_breaking_even_without_existing_type(self):
        finding = one('op.alter_column("t", "c", new_column_name="d")')
        assert finding.severity is Severity.BREAKING
        assert "Coluna `c` de `t` renomeada" in finding.reason

    def test_nothing_the_classifier_recognizes_is_unknown(self):
        finding = one('op.alter_column("t", "c", existing_type=sa.Integer())')
        assert finding.severity is Severity.UNKNOWN

    def test_the_worst_change_wins(self):
        assert (
            severity_of(
                'op.alter_column("t", "c", type_=sa.Text(), existing_type=sa.Integer(),'
                ' server_default="x")'
            )
            is Severity.BREAKING
        )

    def test_unpacked_arguments_are_unknown(self):
        finding = one("op.alter_column(**SPEC)")
        assert finding.severity is Severity.UNKNOWN
        assert "desempacotados" in finding.reason

    def test_positional_arguments_are_read_by_position(self):
        # Uma chamada só com posicionais, cuja resposta é diferente da regra crua
        # da linha: `nullable=False` (posição 2) sobre `existing_nullable=True`
        # (posição 9). Se a leitura por posição parar de funcionar, sai o
        # `unknown` da tabela em vez deste `breaking`.
        finding = one(
            'op.alter_column("t", "c", False, False, False, None, None,'
            " sa.Integer(), None, True)"
        )
        assert finding.severity is Severity.BREAKING
        assert "Coluna `c` de `t` passou a NOT NULL" in finding.reason

    @pytest.mark.parametrize(
        "upgrade",
        [
            # Os sentinelas de "não especificado" do próprio Alembic.
            'op.alter_column("t", "c", new_column_name=None, existing_type=sa.Integer())',
            'op.alter_column("t", "c", type_=None, existing_type=sa.Integer())',
            'op.alter_column("t", "c", server_default=False, existing_type=sa.Integer())',
        ],
    )
    def test_an_explicit_sentinel_is_not_read_as_a_change(self, upgrade):
        finding = one(upgrade)
        assert finding.severity is Severity.UNKNOWN, finding
        assert "não reconhece" in finding.reason

    def test_a_full_positional_call_with_sentinels_reports_only_the_type_change(self):
        # A forma que o autogenerate escreve quando só o tipo muda: `nullable`,
        # `comment`, `server_default` e `new_column_name` chegam como sentinela.
        finding = one(
            'op.alter_column("t", "c", None, False, False, None, sa.Text(), sa.Integer())'
        )
        assert finding.severity is Severity.BREAKING
        assert "Tipo da coluna `c` de `t` alterado" in finding.reason

    def test_a_new_name_the_classifier_cannot_read_is_unknown(self):
        # Mesma ilegibilidade que `unique=IS_UNIQUE`, mesma política.
        finding = one('op.alter_column("t", "c", new_column_name=NEW)')
        assert finding.severity is Severity.UNKNOWN
        assert "renomeada para um nome que o classificador não consegue ler" in finding.reason

    def test_dropping_the_default_is_still_a_change(self):
        # `server_default=None` é DROP DEFAULT; só `False` é o sentinela.
        assert (
            severity_of('op.alter_column("t", "c", existing_type=sa.Integer(),'
                        " server_default=None)")
            is Severity.CONTROLLED
        )

    def test_an_explicit_none_existing_type_is_no_prior_state(self):
        # `nullable=True` de propósito: é a entrada cuja resposta muda se
        # `existing_type=None` passar a valer como estado anterior conhecido
        # (viraria `controlled`, "passou a aceitar NULL"). Com `nullable=False`
        # o teste passaria dos dois jeitos e não afirmaria nada.
        finding = one('op.alter_column("t", "c", nullable=True, existing_type=None)')
        assert finding.severity is Severity.UNKNOWN
        assert "não conhece a definição anterior" in finding.reason


